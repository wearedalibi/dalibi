    /** Codes ISO valides (pour la validation). */
    public static function codes(): array
    {
        return array_keys(self::all());
    }

    /** Nom lisible d'un code pays (repli sur le code si inconnu). */
    public static function name(?string $code): string
    {
        $code = $code ?: self::DEFAULT;

        return self::all()[$code] ?? $code;
    }

    /**
     * Options pour un select, triées par nom.
     *
     * @return array<int, array{code: string, name: string}>
     */
    public static function options(): array
    {
        $all = self::all();
        asort($all);

        return array_map(
            static fn (string $code): array => ['code' => $code, 'name' => $all[$code]],
            array_keys($all),
        );
    }
